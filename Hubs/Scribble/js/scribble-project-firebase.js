/* ══════════════════════════════════════════════════
   LOG HELPERS
   itemId is optional — when supplied it is stored on
   the log doc so getItemLogs() can filter by it.
══════════════════════════════════════════════════ */
/* ══════════════════════════════════════════════════
   LOG TAXONOMY
   Every action string in Scribble is generated by this
   codebase, so kind/weight can be classified at write
   time from the sentence itself — no need to touch all
   28 call sites and risk missing one.

   weight 3 = milestone   (create, rename, delete, version)
   weight 2 = normal      (move, copy, link, record, tag)
   weight 1 = noise       (content autosave)

   Nothing is ever dropped. Weight 1 is written exactly
   like the rest and simply hidden by default, so the
   stats pipe keeps every data point.
══════════════════════════════════════════════════ */
const LOG_RULES = [
    [/^Created (module|section|file):/i,        'create',  3],
    [/^Duplicated from /i,                      'create',  3],
    [/^Promoted from module /i,                 'create',  3],
    [/was promoted to its own project\.$/i,     'move',    3],
    [/^Renamed /i,                              'rename',  3],
    [/^Merged /i,                               'merge',   3],
    [/^Moved to bin\.$/i,                       'delete',  3],
    [/removed( \(\d+ items\))?\.$/i,            'delete',  3],
    [/^Permanently deleted link /i,             'delete',  3],
    [/^Restored from bin\.$/i,                  'restore', 3],
    [/^Saved version history:/i,                'version', 3],
    [/^Updated content\.$/i,                    'content', 1],
    [/^(Created link to|Linked to another)/i,   'link',    2],
    [/linked in\.$/i,                           'link',    2],
    [/^Link followed /i,                        'link',    2],
    [/^(Recorded |Removed .*(link|path))/i,     'record',  2],
    [/^Updated tags\.$/i,                       'tag',     2],
    [/^Updated project description\.$/i,        'meta',    2],
    [/^(Moved to '|Received from another)/i,    'move',    2],
    [/moved (out to|in)\.?/i,                   'move',    2],
    [/^(Created a copy to|Copied from)/i,       'copy',    2],
    [/copied in from /i,                        'copy',    2],
];

function classifyAction(action) {
    const text = String(action || '');
    for (const [re, kind, weight] of LOG_RULES) {
        if (re.test(text)) return { kind, weight };
    }
    return { kind: 'meta', weight: 2 };
}

/*
 * ACTOR
 * Scribble has no auth, so "who" is really "which surface wrote
 * this" — the project page, the editor, the bin, or LifeHub
 * calling in later. Each page can set window.SCRIBBLE_ACTOR on
 * load. Shaped as an object now so a real user id can slot in
 * without another migration.
 */
function currentActor() {
    const a = (typeof window !== 'undefined' && window.SCRIBBLE_ACTOR) || {};
    return {
        id:      a.id      || 'local',
        name:    a.name    || 'You',
        surface: a.surface || 'scribble',
    };
}

/*
 * ITEM INDEX — 30s cache
 * Resolving an item's name and path needs the folder tree. Log
 * writes arrive in bursts (one bin delete writes dozens), so a
 * short-lived cache turns N×3 collection reads into 3.
 */
const _idxCache = new Map();
const IDX_TTL   = 30000;

async function _getItemIndex(pid) {
    const hit = _idxCache.get(pid);
    if (hit && (Date.now() - hit.at) < IDX_TTL) return hit.idx;

    const [projSnap, modSnap, secSnap, fileSnap] = await Promise.all([
        getDoc(doc(db, 'projects', pid)),
        getDocs(collection(db, 'projects', pid, 'modules')),
        getDocs(collection(db, 'projects', pid, 'sections')),
        getDocs(collection(db, 'projects', pid, 'files'))
    ]);

    const map = new Map();
    modSnap.docs.forEach(d  => map.set(d.id, { itemType: 'module',  ...d.data() }));
    secSnap.docs.forEach(d  => map.set(d.id, { itemType: 'section', ...d.data() }));
    fileSnap.docs.forEach(d => map.set(d.id, { itemType: 'file',    ...d.data() }));

    const idx = {
        projectName: projSnap.exists() ? (projSnap.data().name || 'Project') : 'Project',
        map
    };
    _idxCache.set(pid, { at: Date.now(), idx });
    return idx;
}

function invalidateItemIndex(pid) { _idxCache.delete(pid); }

async function resolveItemMeta(pid, itemId) {
    if (!itemId) return null;
    try {
        const idx  = await _getItemIndex(pid);
        const item = idx.map.get(itemId);
        if (!item) return null;

        /* Walk up to build the readable path — this is the piece that
           was missing entirely: logs stored itemId and the reader threw
           it away, so every line pointed at nothing. */
        const parts = [];
        let cur = item.parentId || null;
        const seen = new Set();
        while (cur && !seen.has(cur)) {
            seen.add(cur);
            const anc = idx.map.get(cur);
            if (!anc) break;
            parts.unshift(anc.name || 'Untitled');
            cur = anc.parentId || null;
        }

        return {
            itemType: item.itemType,
            itemName: item.name || 'Untitled',
            fileType: item.itemType === 'file' ? (item.type || null) : null,
            itemPath: [idx.projectName, ...parts].join(' / '),
            isSymlink: item.isSymlink === true,
        };
    } catch (e) { return null; }
}


/*
 * writeProjectLog — same signature as before, so all 28 existing
 * call sites keep working untouched. `meta` is optional and only
 * needed when the caller knows better than the classifier.
 *
 * Legacy log docs (no kind/weight/itemName) are left exactly as
 * they are. The reader treats anything missing `kind` as legacy
 * and renders it plainly — no backfill, no write pass over old data.
 */
async function writeProjectLog(pid, action, itemId, meta) {
    const cls   = classifyAction(action);
    const actor = currentActor();

    const entry = {
        action,
        ...nowFields('timestamp'),
        kind:      (meta && meta.kind)   || cls.kind,
        weight:    (meta && meta.weight) || cls.weight,
        actorId:      actor.id,
        actorName:    actor.name,
        actorSurface: actor.surface,
        schema: 2,
    };

    if (itemId) {
        entry.itemId = itemId;
        const resolved = (meta && meta.itemName)
            ? meta
            : await resolveItemMeta(pid, itemId);
        if (resolved) {
            entry.itemType  = resolved.itemType  || null;
            entry.itemName  = resolved.itemName  || null;
            entry.fileType  = resolved.fileType  || null;
            entry.itemPath  = resolved.itemPath  || null;
            /* A link moving is not the same event as its target moving —
               the command center will want to tell those apart. */
            if (resolved.isSymlink) entry.kind = 'link';
        }
    }

    add(collection(db, 'projects', pid, 'logs'), entry);
}
async function writeGlobalLog(filename) {
    add(collection(db, 'logs'), { filename, ...nowFields('timestamp') });
}

/*
 * logItemAction — generic, exposed logger so OTHER modules
 * (editor-firebase.js for version saves, scribble-export.js for
 * exports, project-app.js for imports) can write a custom line
 * to an item's own log without duplicating Firestore code.
 * Deliberately skips writeGlobalLog — these are fine-grained,
 * frequent-ish actions that would flood the sidebar's "last 7
 * days" feed if they counted as headline activity.
 */
async function logItemAction(pid, itemId, action) {
    await writeProjectLog(pid, action, itemId);
}

/*
 * logDailyUpdate — the "Updated" stamp, deduped to ONE line per
 * calendar day per item. Looks for an existing "Updated content."
 * entry for this item from today; if found, bumps its timestamp
 * forward (so it always reflects the LAST edit of the day) instead
 * of creating a new line. Only creates a fresh entry once per day.
 *
 * NOTE: this query needs a Firestore composite index on
 * projects/{pid}/logs → (itemId ASC, action ASC, timestamp DESC).
 * Firestore will throw with a direct "create this index" link in
 * the console the first time this runs — click it once and it's
 * a one-time setup.
 */
async function logDailyUpdate(pid, itemId) {
    try {
        const startOfDay = new Date();
        startOfDay.setHours(0, 0, 0, 0);
        const q = query(
            collection(db, 'projects', pid, 'logs'),
            where('itemId', '==', itemId),
            where('action', '==', 'Updated content.'),
            where('timestamp', '>=', startOfDay),
            orderBy('timestamp', 'desc'),
            limit(1)
        );
        const snap = await getDocs(q);
        if (!snap.empty) {
            await merge(doc(db, 'projects', pid, 'logs', snap.docs[0].id), { ...nowFields('timestamp') });
        } else {
            add(collection(db, 'projects', pid, 'logs'), {
                action: 'Updated content.', itemId, ...nowFields('timestamp')
            });
        }
    } catch (e) {
        console.warn('[logDailyUpdate]', e.message);
    }
}

