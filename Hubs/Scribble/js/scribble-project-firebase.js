async function deleteSymlink(pid, itemType, symlinkId) {
    const collMap = { module: 'modules', section: 'sections', file: 'files' };
    const coll = collMap[itemType];
    if (!coll) return;
    const snap = await getDoc(doc(db, 'projects', pid, coll, symlinkId));
    const name = snap.exists() ? (snap.data().name || 'Untitled') : 'Untitled';
    await remove(doc(db, 'projects', pid, coll, symlinkId));
    await writeProjectLog(pid, "Permanently deleted link '" + name + "'.", symlinkId);
    await writeGlobalLog(name);
}

