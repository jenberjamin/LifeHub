/* ══════════════════════════════════════════════════
   RENAME
══════════════════════════════════════════════════ */
async function renameItem(pid, itemType, id, oldName, newName) {
    invalidateItemIndex(pid);
    touchAncestors(pid, null, { force: true });
    const coll = COLL[itemType]; if (!coll) return;
    newName = newName.trim();

    // Compare against siblings in the item's OWN folder, excluding itself.
    const self = await getDoc(doc(db, 'projects', pid, coll, id));
    if (self.exists()) {
        const d = self.data();
        const clash = await findItemClash(pid, itemType, d.parentId || null, newName, d.type, id);
        if (clash) {
            throw _dupError("'" + newName + "' is already taken here.", clash);
        }
    }

    await merge(doc(db, 'projects', pid, coll, id), {
        name: newName, ...nowFields('updatedAt')
    });
    await writeProjectLog(pid, "Renamed '" + (oldName || 'Untitled') + "' to '" + newName + "'.", id);
    await writeGlobalLog(newName);
}

/* ══════════════════════════════════════════════════
   PIN  — toggles pinned field, floats card to top
══════════════════════════════════════════════════ */
async function pinItem(pid, itemType, id, pinned) {
    const coll = COLL[itemType];
    if (!coll) return;
    await merge(doc(db, 'projects', pid, coll, id), {
        pinned: pinned,
        ...nowFields('updatedAt')
    });
    await writeProjectLog(
        pid,
        (pinned ? 'Pinned' : 'Unpinned') + " " + itemType + ": '" + id + "'",
        id
    );
}

/* ══════════════════════════════════════════════════
   DUPLICATE  — shallow clone into the same parent
══════════════════════════════════════════════════ */
async function duplicateItem(pid, itemType, id, itemData, parentId) {
    const coll = COLL[itemType];
    if (!coll) return;

    /* Duplicating the same thing twice used to make two identical
       "Copy of X". Walks up to the first free name instead —
       refusing would be wrong when you asked for a copy. The file
       type has to be settled first, since for files the name is only
       taken when the extension matches too. */
    const dupType  = itemType === 'file' ? (itemData.type || 'txt') : null;
    const copyName = await freeItemName(
        pid, itemType, parentId || null,
        'Copy of ' + (itemData.name || 'Untitled'), dupType);

    const base = {
        projectId:   pid,
        parentId:    parentId || null,
        name:        copyName,
        description: itemData.description || '',
        pinned:      false,
        ...nowFields('createdAt'),
        ...nowFields('updatedAt')
    };

    /* Carry over file-specific fields */
    if (itemType === 'file') {
        base.type   = dupType;
        base.colour = itemData.colour || null;
    }

    // Carry over symlink pointer so duplicating a link produces another link
    if (itemData.isSymlink) {
        base.isSymlink         = true;
        base.targetId          = itemData.targetId;
        base.targetProjectId   = itemData.targetProjectId;
        base.targetProjectName = itemData.targetProjectName || '';
        base.targetType        = itemData.targetType;
    }

    const ref = add(collection(db, 'projects', pid, coll), base);
    await writeProjectLog(pid, "Duplicated from '" + (itemData.name || 'Untitled') + "'.", ref.id);
    await writeGlobalLog(copyName);
    return ref.id;
}

