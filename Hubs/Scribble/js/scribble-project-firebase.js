/*
 * getItemLogsRecursive — for MODULE/SECTION only. A module's own log
 * should show everything happening anywhere in its subtree (children,
 * grandchildren, etc.), not just entries tagged with the module's own
 * id. Files skip this entirely and fall through to plain getItemLogs,
 * since a file can't have children.
 */
async function getItemLogsRecursive(pid, itemType, itemId) {
    if (itemType === 'file') return getItemLogs(pid, itemId);

    try {
        const [modSnap, secSnap, fileSnap] = await Promise.all([
            getDocs(collection(db, 'projects', pid, 'modules')),
            getDocs(collection(db, 'projects', pid, 'sections')),
            getDocs(collection(db, 'projects', pid, 'files'))
        ]);
        const allItems = [
            ...modSnap.docs.map(d  => ({ id: d.id, ...d.data() })),
            ...secSnap.docs.map(d  => ({ id: d.id, ...d.data() })),
            ...fileSnap.docs.map(d => ({ id: d.id, ...d.data() }))
        ];

        /* BFS: this item + every descendant, any type, any depth */
        const ids   = [itemId];
        const queue = [itemId];
        const seen  = new Set([itemId]);
        while (queue.length) {
            const cur = queue.shift();
            allItems.filter(x => x.parentId === cur && !seen.has(x.id)).forEach(child => {
                seen.add(child.id); ids.push(child.id); queue.push(child.id);
            });
        }

        /* Firestore 'in' queries cap at 30 values — chunk large subtrees */
        const chunks = [];
        for (let i = 0; i < ids.length; i += 30) chunks.push(ids.slice(i, i + 30));

        const M = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
        let results = [];
        for (const chunk of chunks) {
            const q = query(
                collection(db, 'projects', pid, 'logs'),
                where('itemId', 'in', chunk),
                orderBy('timestamp', 'desc'),
                limit(50)
            );
            const snap = await getDocs(q);
            results = results.concat(snap.docs.map(d => {
                const data = d.data();
                /* whenMs — see the note in getProjectLogsPaged. */
                const _tms = whenMs(data, 'timestamp');
                const ts   = _tms ? new Date(_tms) : null;
                const timeStr = ts
                    ? M[ts.getMonth()] + ' ' + ts.getDate() + ', ' + ts.getFullYear() +
                      '  ' + ts.getHours().toString().padStart(2, '0') + ':' +
                      ts.getMinutes().toString().padStart(2, '0')
                    : '—';
                return { action: data.action || '', timeStr, _ms: ts ? ts.getTime() : 0 };
            }));
        }
        results.sort((a, b) => b._ms - a._ms);
        return results.slice(0, 50).map(r => ({ action: r.action, timeStr: r.timeStr }));
    } catch(e) {
        console.warn('[getItemLogsRecursive]', e.message);
        return [];
    }
}

