/* ══════════════════════════════════════════════════
   REAL-TIME LISTENER
══════════════════════════════════════════════════ */
function listenProjectContents(projectId, callback) {
    const state  = { modules: [], sections: [], files: [] };
    const notify = () => callback({
        modules:  state.modules.slice(),
        sections: state.sections.slice(),
        files:    state.files.slice()
    });
    const q = (sub) =>
        query(collection(db, 'projects', projectId, sub), orderBy('createdAt', 'asc'));

    const u1 = onSnapshot(q('modules'),  snap => {
        state.modules  = snap.docs.map(d => ({ id: d.id, ...d.data() })).filter(d => !d.deleted && !d.archived);
        notify();
    }, err => console.warn('[Project] modules:', err.message));
    const u2 = onSnapshot(q('sections'), snap => {
        state.sections = snap.docs.map(d => ({ id: d.id, ...d.data() })).filter(d => !d.deleted && !d.archived);
        notify();
    }, err => console.warn('[Project] sections:', err.message));
    const u3 = onSnapshot(q('files'),    snap => {
        state.files    = snap.docs.map(d => ({ id: d.id, ...d.data() })).filter(d => !d.deleted && !d.archived);
        notify();
    }, err => console.warn('[Project] files:', err.message));

    return () => { u1(); u2(); u3(); };
}

/* ══════════════════════════════════════════════════
   DUPLICATE GUARDS

   ── CORRECTED 2026-09-17 ──────────────────────────
   This header used to say "Exact-match only: names are
   compared after .trim(), case-sensitive. 'Notes' and
   'notes' are two names." That was never true of the
   code below it — findItemClash calls normName(), which
   lowercases. 'Notes' and 'notes' are ONE name, here and
   everywhere else in Scribble. See the NAME
   NORMALISATION block further down, which has always
   described it correctly.

   For files the identity is name + type, so notes.txt
   and notes.md can coexist but two notes.txt cannot.

   Reads the folder's siblings with a single-field
   parentId query and filters in memory — deliberately
   avoids a composite index so this needs zero Firestore
   setup on your side.
══════════════════════════════════════════════════ */
/*
 * findItemClash — the one that does the work.
 * Returns { id, name, status } or null.
 * status: 'live' | 'archived' | 'bin'
 *
 * SCOPE is the folder, not the project. "Notes.txt" in Module A
 * and "Notes.txt" in Module B are two different files and always
 * were — the parentId filter below is what keeps them apart.
 *
 * Binned and archived siblings still hold their name, for the same
 * reason projects do: they come back, and a collision discovered at
 * restore time is expensive to fix. The caller is told WHERE the
 * clash lives so a name never looks taken by nothing.
 */
async function findItemClash(pid, itemType, parentId, name, type, excludeId) {
    const coll = COLL[itemType]; if (!coll) return null;
    const target = normName(name);
    if (!target) return null;

    const snap = await getDocs(query(
        collection(db, 'projects', pid, coll),
        where('parentId', '==', parentId || null)
    ));

    for (const d of snap.docs) {
        if (d.id === excludeId) continue;              // renaming an item to itself
        const data = d.data();

        if (normName(data.name) !== target) continue;
        if (itemType === 'file' && type &&
            normType(data.type) !== normType(type)) continue;   // name + type is the identity

        return {
            id:     d.id,
            name:   data.name || '',
            type:   data.type || null,
            status: data.deleted ? 'bin' : (data.archived ? 'archived' : 'live')
        };
    }
    return null;
}

/* Boolean wrapper — every existing caller still works. */
async function nameExists(pid, itemType, parentId, name, type, excludeId) {
    return !!(await findItemClash(pid, itemType, parentId, name, type, excludeId));
}

/*
 * freeItemName — first free name at or after `base`.
 *   "Notes"  →  "Notes (2)"  →  "Notes (3)" …
 *
 * For COPY and DUPLICATE only. Refusing there would be wrong — you
 * asked for a second one, so the answer is a name, not an error.
 * Move and symlink refuse instead, because there you picked a
 * specific destination for a specific thing and silently renaming
 * it would hide the collision rather than report it.
 *
 * Capped so a bad read can never spin this forever.
 */
async function freeItemName(pid, itemType, parentId, base, type) {
    if (!(await findItemClash(pid, itemType, parentId, base, type))) return base;
    for (let n = 2; n < 100; n++) {
        const candidate = base + ' (' + n + ')';
        if (!(await findItemClash(pid, itemType, parentId, candidate, type))) return candidate;
    }
    return base + ' (' + Date.now() + ')';
}

/* ══════════════════════════════════════════════════
   NAME NORMALISATION
   Case is ignored; everything else is significant.

       Notes / notes / nOtEs      same name
       "Life Hub" / "LifeHub"     different
       "Life-hub" / "LifeHub"     different
       "Life.hub" / "Life-hub"    different

   So this only trims the ends and lowercases. Spaces,
   hyphens and dots inside a name are real characters and
   are compared as typed. (An earlier version collapsed
   runs of whitespace, which would have wrongly merged
   "Life Hub" with "Life  Hub".)

   Display is untouched — only the COMPARISON is loose.
   Whatever capitalisation you type is what gets stored.
══════════════════════════════════════════════════ */
function normName(s) {
    return String(s == null ? '' : s).trim().toLowerCase();
}

function normType(s) {
    return String(s == null ? '' : s).trim().toLowerCase();
}

/* One link per folder: is this exact target already linked in here? */
async function symlinkExists(destPid, destParentId, itemType, targetId) {
    const coll = COLL[itemType]; if (!coll) return false;

    const snap = await getDocs(query(
        collection(db, 'projects', destPid, coll),
        where('parentId', '==', destParentId || null)
    ));

    return snap.docs.some(function(d) {
        const data = d.data();
        if (data.deleted) return false;    // a binned link isn't in the folder
        return data.isSymlink === true && data.targetId === targetId;
    });
}

/* `clash` rides along so the caller can open the shared
   modal and say WHERE the name is taken, rather than just
   printing a sentence. */
function _dupError(msg, clash) {
    const e = new Error(msg);
    e.code  = 'duplicate-name';
    if (clash) e.clash = clash;
    return e;
}

/* ══════════════════════════════════════════════════
   CREATE  (stores projectId on each item)
══════════════════════════════════════════════════ */
async function createModule(pid, parentId, name, desc) {
    const clash = await findItemClash(pid, 'module', parentId, name);
    if (clash) {
        throw _dupError("A module named '" + name.trim() + "' already exists here.", clash);
    }
    const ref = add(collection(db, 'projects', pid, 'modules'), {
        projectId: pid, parentId: parentId || null,
        name: name.trim(), description: desc.trim(),
        pinned: false,
        ...nowFields('createdAt'), ...nowFields('updatedAt')
    });
    await writeProjectLog(pid, "Created module: '" + name.trim() + "'", ref.id);
    await writeGlobalLog(name.trim());
    touchAncestors(pid, parentId, { force: true });
    return ref.id;
}
async function createSection(pid, parentId, name, desc) {
    const clash = await findItemClash(pid, 'section', parentId, name);
    if (clash) {
        throw _dupError("A section named '" + name.trim() + "' already exists here.", clash);
    }
    const ref = add(collection(db, 'projects', pid, 'sections'), {
        projectId: pid, parentId: parentId || null,
        name: name.trim(), description: desc.trim(),
        pinned: false,
        ...nowFields('createdAt'), ...nowFields('updatedAt')
    });
    await writeProjectLog(pid, "Created section: '" + name.trim() + "'", ref.id);
    await writeGlobalLog(name.trim());
    touchAncestors(pid, parentId, { force: true });
    return ref.id;
}
async function createFile(pid, parentId, name, type, colour, desc) {
    const clash = await findItemClash(pid, 'file', parentId, name, type);
    if (clash) {
        throw _dupError("A file named '" + name.trim() + "." + type + "' already exists here.", clash);
    }
    const ref = add(collection(db, 'projects', pid, 'files'), {
        projectId: pid, parentId: parentId || null,
        name: name.trim(), type, colour: colour || null,
        description: (desc || '').trim(),
        pinned: false,
        ...nowFields('createdAt'), ...nowFields('updatedAt')
    });
    const label = type === 'colour'
        ? name.trim() + ' [colour]'
        : name.trim() + '.' + type;
    await writeProjectLog(pid, "Created file: '" + label + "'", ref.id);
    await writeGlobalLog(name.trim());
    touchAncestors(pid, parentId, { force: true });
    return ref.id;
}

