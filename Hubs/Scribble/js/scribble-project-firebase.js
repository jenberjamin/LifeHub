/* ══════════════════════════════════════════════════
   MOVE ITEM
   Same-project: update parentId only.
   Cross-project: BFS copy descendants → target,
   then hard-delete originals from source.
══════════════════════════════════════════════════ */
async function moveItem(sourcePid, itemType, itemId, targetPid, targetParentId) {
    const coll = COLL[itemType];
    if (!coll) return;
    const now = nowFields('updatedAt');

    /* ── Same project: just reparent ── */
    if (sourcePid === targetPid) {
        const snap = await getDoc(doc(db, 'projects', sourcePid, coll, itemId));
        if (!snap.exists()) return;
        const itemData  = snap.data();
        const name      = itemData.name || 'Untitled';
        const oldParent = itemData.parentId || null;

        /* Nothing to do — and checking would find the item itself. */
        if (oldParent === (targetParentId || null)) return;

        /* A move keeps its name, so a taken name is a refusal, not a
           rename. excludeId guards the item against matching itself. */
        const clash = await findItemClash(
            sourcePid, itemType, targetParentId || null, name, itemData.type, itemId);
        if (clash) {
            throw _dupError(
                "'" + name + "' already exists in the destination folder.", clash);
        }

        const [modSnap, secSnap] = await Promise.all([
            getDocs(collection(db, 'projects', sourcePid, 'modules')),
            getDocs(collection(db, 'projects', sourcePid, 'sections'))
        ]);
        const folders = [
            ...modSnap.docs.map(d => ({ id: d.id, ...d.data() })),
            ...secSnap.docs.map(d => ({ id: d.id, ...d.data() }))
        ];
        const projSnap    = await getDoc(doc(db, 'projects', sourcePid));
        const projectName = projSnap.exists() ? (projSnap.data().name || 'Project') : 'Project';
        const destPath = buildPath(projectName, targetParentId || null, folders, name);

        await merge(doc(db, 'projects', sourcePid, coll, itemId), {
            parentId: targetParentId || null, ...now
        });

        await writeProjectLog(sourcePid, "Moved to '" + destPath + "'.", itemId);

        /* Parent-scoped visibility — old folder sees it leave, new folder sees it arrive */
        if (oldParent && oldParent !== (targetParentId || null)) {
            await writeProjectLog(sourcePid, "'" + name + "' moved out to '" + destPath + "'.", oldParent);
        }
        if (targetParentId && targetParentId !== oldParent) {
            await writeProjectLog(sourcePid, "'" + name + "' moved in.", targetParentId);
        }

        await writeGlobalLog(name);
        return;
    }

    /* ── Cross-project: BFS collect + copy + delete ── */
    const [modSnap, secSnap, fileSnap] = await Promise.all([
        getDocs(collection(db, 'projects', sourcePid, 'modules')),
        getDocs(collection(db, 'projects', sourcePid, 'sections')),
        getDocs(collection(db, 'projects', sourcePid, 'files'))
    ]);
    const allItems = [
        ...modSnap.docs.map(d  => ({ id: d.id, _subcol: 'modules',  ...d.data() })),
        ...secSnap.docs.map(d  => ({ id: d.id, _subcol: 'sections', ...d.data() })),
        ...fileSnap.docs.map(d => ({ id: d.id, _subcol: 'files',    ...d.data() }))
    ].filter(x => !x.deleted);

    const root = allItems.find(x => x.id === itemId);
    if (!root) return;
    const oldParent = root.parentId || null;

    /* Only the ROOT lands in the destination folder — every descendant
       lands inside the freshly made copy of its own parent, where
       nothing can already be sitting. So the root is the only name
       that can collide, and the only one worth checking. */
    const rootClash = await findItemClash(
        targetPid, itemType, targetParentId || null, root.name || 'Untitled', root.type);
    if (rootClash) {
        throw _dupError(
            "'" + (root.name || 'Untitled') + "' already exists in the destination folder.",
            rootClash);
    }

    /* BFS — preserves parent-before-child order */
    const toMove = [root];
    const queue  = [itemId];
    const seen   = new Set([itemId]);
    while (queue.length) {
        const cur = queue.shift();
        allItems.filter(x => x.parentId === cur && !seen.has(x.id)).forEach(function(child) {
            seen.add(child.id);
            toMove.push(child);
            queue.push(child.id);
        });
    }

    /* Copy to target, building an id map for child reparenting */
    const idMap = {};
    for (const item of toMove) {
        const newParent = item.id === itemId
            ? (targetParentId || null)
            : (idMap[item.parentId] || null);

        const newData = Object.assign({}, item, {
            projectId: targetPid,
            parentId:  newParent,
            ...now
        });
        delete newData.id;
        delete newData._subcol;

        const ref = add(collection(db, 'projects', targetPid, item._subcol), newData);
        idMap[item.id] = ref.id;
    }

    /* Hard-delete from source (leaves first → reverse BFS) */
    for (const item of [...toMove].reverse()) {
        await remove(doc(db, 'projects', sourcePid, item._subcol, item.id));
    }

    /* Exact destination path, resolved in the TARGET project's own folders */
    const [tgtModSnap, tgtSecSnap, tgtProjSnap] = await Promise.all([
        getDocs(collection(db, 'projects', targetPid, 'modules')),
        getDocs(collection(db, 'projects', targetPid, 'sections')),
        getDoc(doc(db, 'projects', targetPid))
    ]);
    const targetFolders = [
        ...tgtModSnap.docs.map(d => ({ id: d.id, ...d.data() })),
        ...tgtSecSnap.docs.map(d => ({ id: d.id, ...d.data() }))
    ];
    const targetProjectName = tgtProjSnap.exists() ? (tgtProjSnap.data().name || 'Project') : 'Project';
    const destPath = buildPath(targetProjectName, targetParentId || null, targetFolders, root.name || 'Untitled');

    await writeProjectLog(sourcePid, "Moved to '" + destPath + "'.", itemId);
    if (oldParent) {
        await writeProjectLog(sourcePid, "'" + (root.name || 'Untitled') + "' moved out to '" + destPath + "'.", oldParent);
    }
    await writeProjectLog(targetPid, "Received from another project.", idMap[itemId]);
    if (targetParentId) {
        await writeProjectLog(targetPid, "'" + (root.name || 'Untitled') + "' moved in.", targetParentId);
    }
    await writeGlobalLog(root.name || 'Untitled');

    /* The cached name/path index for both projects is now wrong: this
       branch deleted documents from one and created them in the other.

       Cleared for what comes AFTER this line, not for the log lines
       above — a repointed link can live in the target project itself
       (a symlink that sat inside the moved subtree), and resolving its
       name needs an index that knows the new ids exist.

       It does nothing for the lines already written above, and cannot:
       invalidating a cache does not retroactively fix a log entry.
       Those have their own quirk, left alone deliberately — the
       sourcePid line names an item this branch just deleted, and the
       stale index is the only thing that can still name it. */
    invalidateItemIndex(sourcePid);
    invalidateItemIndex(targetPid);

    /* ── SYMLINK REPOINTING, added 2026-09-17 ──────────────────
       Every id in this subtree changed, so every pointer aimed at
       any of them is now dangling. See repointSymlinks().

       NOT awaited, matching the cascade in softDeleteItem: the move
       itself is already queued and the grid has moved on, so making
       the caller wait on a collection-group query that usually finds
       nothing would tax every move for the sake of the rare one.
       Safe here specifically because nothing navigates away after a
       move — doMoveItem and doDragAction both just close the modal.
       promoteModule is the opposite case and awaits; see the note
       there. */
    (async function repoint() {
        try {
            const n = await repointSymlinks(
                idMap, targetPid, targetProjectName,
                "across to '" + targetProjectName + "'");
            if (n) {
                console.info('[Scribble] ' + n + ' link(s) followed "' +
                             (root.name || 'Untitled') + '" to ' + targetProjectName + '.');
            }
        } catch (e) {
            console.warn('[moveItem] symlink repoint:', e.message);
        }
    })();
}

/* ══════════════════════════════════════════════════
   PROMOTE MODULE → PROJECT
   A module that has outgrown its parent becomes a
   top-level project of its own. Its children are lifted
   to the new project's ROOT and the module shell itself
   disappears — it hasn't moved, it has become the
   project, so keeping an empty module inside would just
   add a folder nobody asked for.

   Same copy-then-delete shape as the cross-project
   branch of moveItem(): ids are minted fresh in the
   destination, so anything pointing at the old ids
   (symlinks) is left behind exactly as a cross-project
   move leaves it.
══════════════════════════════════════════════════ */
/* Project names are global, unlike item names, which are
   scoped to their folder. Binned and archived projects
   still hold their name — they come back. */
async function findProjectNameClash(name) {
    const target = normName(name);
    if (!target) return null;
    const snap = await getDocs(collection(db, 'projects'));
    for (const d of snap.docs) {
        const data = d.data();
        if (normName(data.name) !== target) continue;
        return {
            id:     d.id,
            name:   data.name || '',
            status: data.deleted ? 'bin' : (data.archived ? 'archived' : 'live')
        };
    }
    return null;
}

async function promoteModule(pid, moduleId, newName, description) {
    const modDoc = await getDoc(doc(db, 'projects', pid, 'modules', moduleId));
    if (!modDoc.exists()) throw new Error('That module no longer exists.');
    const moduleData = modDoc.data();

    /* A link is a pointer, not the thing — promoting it would move
       nothing and delete the pointer. */
    if (moduleData.isSymlink) {
        throw new Error('This is a link to a module in another project. Promote the original instead.');
    }

    const name = String(newName == null ? (moduleData.name || '') : newName).trim() || 'Untitled';
    const clash = await findProjectNameClash(name);
    if (clash) {
        const e = new Error("A project named '" + clash.name + "' already exists" +
            (clash.status === 'bin'      ? ' in the recycle bin.' :
             clash.status === 'archived' ? ' in the archive.' : '.'));
        e.code  = 'duplicate-name';
        e.clash = clash;
        throw e;
    }

    const now       = nowFields('updatedAt');
    const oldParent = moduleData.parentId || null;

    const [modSnap, secSnap, fileSnap] = await Promise.all([
        getDocs(collection(db, 'projects', pid, 'modules')),
        getDocs(collection(db, 'projects', pid, 'sections')),
        getDocs(collection(db, 'projects', pid, 'files'))
    ]);
    const allItems = [
        ...modSnap.docs.map(d  => ({ id: d.id, _subcol: 'modules',  ...d.data() })),
        ...secSnap.docs.map(d  => ({ id: d.id, _subcol: 'sections', ...d.data() })),
        ...fileSnap.docs.map(d => ({ id: d.id, _subcol: 'files',    ...d.data() }))
    ].filter(x => !x.deleted);

    /* BFS from the module, but the module itself is NOT carried over —
       it is the project now. Parent-before-child order, so idMap is
       always populated before a child needs it. */
    const toMove = [];
    const queue  = [moduleId];
    const seen   = new Set([moduleId]);
    while (queue.length) {
        const cur = queue.shift();
        allItems.filter(x => (x.parentId || null) === cur && !seen.has(x.id)).forEach(function(child) {
            seen.add(child.id);
            toMove.push(child);
            queue.push(child.id);
        });
    }

    /* The project has to exist before anything can be written into it.
       newRef mints the id locally, so this holds up offline. */
    const projRef = newRef(collection(db, 'projects'));
    await save(projRef, {
        name:        name,
        description: String(description == null ? (moduleData.description || '') : description).trim(),
        projectId:   projRef.id,
        ...nowFields('createdAt'), ...nowFields('updatedAt'),
        pinned: false, pinnedAt: null
    });
    const newPid = projRef.id;

    /* Copy across — what sat directly in the module now sits at root */
    const idMap = {};
    for (const item of toMove) {
        const newParent = (item.parentId || null) === moduleId
            ? null
            : (idMap[item.parentId] || null);

        const newData = Object.assign({}, item, {
            projectId: newPid,
            parentId:  newParent,
            ...now
        });
        delete newData.id;
        delete newData._subcol;

        const ref = add(collection(db, 'projects', newPid, item._subcol), newData);
        idMap[item.id] = ref.id;
    }

    /* Hard-delete from source: leaves first, then the module shell */
    for (const item of [...toMove].reverse()) {
        await remove(doc(db, 'projects', pid, item._subcol, item.id));
    }
    await remove(doc(db, 'projects', pid, 'modules', moduleId));

    /* The cached name/path index still holds the items just deleted */
    invalidateItemIndex(pid);

    await writeProjectLog(newPid, 'Created the project.');
    await writeProjectLog(newPid, "Promoted from module '" + name + "' (" + toMove.length +
        (toMove.length === 1 ? ' item' : ' items') + ' carried over).');
    await writeProjectLog(pid,
        "'" + name + "' was promoted to its own project.", oldParent || null);
    await writeGlobalLog(name);

    /* ── SYMLINK REPOINTING, added 2026-09-17 ──────────────────
       The module's children were re-minted in the new project and the
       originals hard-deleted, so every pointer at any of them is
       dangling. See repointSymlinks().

       ── AWAITED, UNLIKE moveItem ──────────────────────────────
       This one has to be. doPromoteModule() navigates the browser to
       the new project the instant this resolves, and a page unload
       kills work that is still in flight — a fire-and-forget repoint
       here would simply never happen.

       It also fits what this function already promises: the modal is
       deliberately held open until the write lands, "because a promote
       moves a whole subtree and closing early would leave the grid
       mid-flight with nothing to say why". Waiting for the links is
       the same bargain. */
    try {
        await repointSymlinks(idMap, newPid, name,
            "into its own project '" + name + "'");

        /* The module SHELL has no replacement — it did not move, it
           became the project, and a symlink can only target a module,
           section or file. So there is nothing to repoint these at.
           Recorded rather than deleted: quietly removing someone's
           link is worse than leaving a broken one they can see. */
        await flagBrokenSymlinks([moduleId],
            "'" + name + "' was promoted to its own project, so there is no " +
            'module left to link to');
    } catch (e) {
        /* A failed repoint must not fail the promote — the project is
           already built and its contents are already in it. */
        console.warn('[promoteModule] symlink repoint:', e.message);
    }

    return { projectId: newPid, moved: toMove.length };
}

/* ══════════════════════════════════════════════════
   COPY ITEM  — BFS clone to destination, no deletion
══════════════════════════════════════════════════ */
async function copyItem(sourcePid, itemType, itemId, targetPid, targetParentId) {
    const coll = COLL[itemType];
    if (!coll) return;
    const now = nowFields('updatedAt');

    const [modSnap, secSnap, fileSnap] = await Promise.all([
        getDocs(collection(db, 'projects', sourcePid, 'modules')),
        getDocs(collection(db, 'projects', sourcePid, 'sections')),
        getDocs(collection(db, 'projects', sourcePid, 'files'))
    ]);
    const allItems = [
        ...modSnap.docs.map(d  => ({ id: d.id, _subcol: 'modules',  ...d.data() })),
        ...secSnap.docs.map(d  => ({ id: d.id, _subcol: 'sections', ...d.data() })),
        ...fileSnap.docs.map(d => ({ id: d.id, _subcol: 'files',    ...d.data() }))
    ].filter(x => !x.deleted);

    const root = allItems.find(x => x.id === itemId);
    if (!root) return;

    /* BFS — parent before child */
    const toCopy = [root];
    const queue  = [itemId];
    const seen   = new Set([itemId]);
    while (queue.length) {
        const cur = queue.shift();
        allItems.filter(x => x.parentId === cur && !seen.has(x.id)).forEach(function(child) {
            seen.add(child.id); toCopy.push(child); queue.push(child.id);
        });
    }

    /* Clone to target — "Copy of" prefix only when landing in the same parent */
    const idMap    = {};
    const rootName = root.name || 'Untitled';
    const sameSpot = sourcePid === targetPid &&
        (targetParentId || null) === (root.parentId || null);

    /*
     * Only the root can collide (descendants land inside the new copy
     * of their own parent), so only the root's name is resolved.
     *
     * Landing elsewhere used to keep the original name outright, which
     * silently made a second "Notes.txt" in a folder that already had
     * one. And copying twice into the same spot made two "Copy of X".
     * Both now walk up: "Copy of X (2)", "Notes (2)", and so on.
     */
    const rootBase = sameSpot ? 'Copy of ' + rootName : rootName;
    const rootFinal = await freeItemName(
        targetPid, itemType, targetParentId || null, rootBase, root.type);

    for (const item of toCopy) {
        const newParent = item.id === itemId
            ? (targetParentId || null)
            : (idMap[item.parentId] || null);

        const newName = (item.id === itemId)
            ? rootFinal
            : (item.name || 'Untitled');

        const newData = Object.assign({}, item, {
            name:      newName,
            projectId: targetPid,
            parentId:  newParent,
            ...nowFields('createdAt'),
            ...now,
            pinned:    false
        });
        delete newData.id;
        delete newData._subcol;

        const ref = add(collection(db, 'projects', targetPid, item._subcol), newData);
        idMap[item.id] = ref.id;
    }

    /* Exact destination path, resolved in the TARGET project's own folders */
    const [tgtModSnap, tgtSecSnap, tgtProjSnap] = await Promise.all([
        getDocs(collection(db, 'projects', targetPid, 'modules')),
        getDocs(collection(db, 'projects', targetPid, 'sections')),
        getDoc(doc(db, 'projects', targetPid))
    ]);
    const targetFolders = [
        ...tgtModSnap.docs.map(d => ({ id: d.id, ...d.data() })),
        ...tgtSecSnap.docs.map(d => ({ id: d.id, ...d.data() }))
    ];
    const targetProjectName = tgtProjSnap.exists() ? (tgtProjSnap.data().name || 'Project') : 'Project';
    /* The name the copy ACTUALLY got, not the one it asked for —
       recomputing the label here would report "Copy of X" in the log
       for something that landed as "Copy of X (2)". */
    const copyLabel = rootFinal;
    const destPath  = buildPath(targetProjectName, targetParentId || null, targetFolders, copyLabel);

    /* Original — "created a copy to [exact path]" */
    await writeProjectLog(sourcePid, "Created a copy to '" + destPath + "'.", itemId);

    /* The NEW copy's own log — "Copied from [original]" */
    await writeProjectLog(targetPid, "Copied from '" + rootName + "'.", idMap[itemId]);

    /* Parent-scoped visibility within the destination folder */
    if (targetParentId) {
        await writeProjectLog(targetPid, "'" + copyLabel + "' copied in from '" + rootName + "'.", targetParentId);
    }
    await writeGlobalLog(rootName);
}

/* ══════════════════════════════════════════════════
   SYMLINK — CREATE
   Thin pointer doc in destination. Original untouched.
══════════════════════════════════════════════════ */
async function createSymlink(destPid, destParentId, sourcePid, sourceProjectName, sourceItemId, sourceItemType, sourceName) {
    const collMap = { module: 'modules', section: 'sections', file: 'files' };
    const coll = collMap[sourceItemType];
    if (!coll) return;

    /* One link per folder — re-linking the same target is a no-op mistake,
       not a feature. Checked before the name clash so the message is
       specific about WHY it was refused. */
    if (await symlinkExists(destPid, destParentId, sourceItemType, sourceItemId)) {
        throw _dupError("'" + sourceName + "' is already linked into this folder.");
    }
    /* A link carries its target's name, so a clash is a refusal — there
       is no "Copy of" to fall back on without the link lying about
       what it points at. */
    const linkClash = await findItemClash(destPid, sourceItemType, destParentId, sourceName);
    if (linkClash) {
        throw _dupError(
            "Something named '" + sourceName + "' already exists in the destination folder.",
            linkClash);
    }

    const ref = add(collection(db, 'projects', destPid, coll), {
        projectId:         destPid,
        parentId:          destParentId || null,
        name:              sourceName,
        pinned:            false,
        isSymlink:         true,
        targetProjectId:   sourcePid,
        targetProjectName: sourceProjectName,
        targetId:          sourceItemId,
        targetType:        sourceItemType,
        ...nowFields('createdAt'),
        ...nowFields('updatedAt')
    });
    await writeProjectLog(destPid, "Created link to " + sourceItemType + " '" + sourceName + "'.", ref.id);

    /* Destination folder sees a link arrive within its own boundary */
    if (destParentId) {
        await writeProjectLog(destPid, "'" + sourceName + "' linked in.", destParentId);
    }

    /* The ORIGINAL item's own log records that it was linked elsewhere */
    await writeProjectLog(sourcePid, "Linked to another project.", sourceItemId);

    await writeGlobalLog(sourceName);
    return ref.id;
}

