/* ══════════════════════════════════════════════════
   GENERAL RECORD — project-wide record sheet
   One read of the whole project, every file resolved to
   its full path, so external storage paths can be filled
   in from a single table instead of file-by-file.
══════════════════════════════════════════════════ */
async function getAllFileRecords(pid) {
    const projectSnap = await getDoc(doc(db, 'projects', pid));
    const projectName = projectSnap.exists() ? (projectSnap.data().name || 'Project') : 'Project';

    const [modSnap, secSnap, fileSnap] = await Promise.all([
        getDocs(collection(db, 'projects', pid, 'modules')),
        getDocs(collection(db, 'projects', pid, 'sections')),
        getDocs(collection(db, 'projects', pid, 'files'))
    ]);

    /* Folders are needed only to resolve each file's path. */
    const folders = [
        ...modSnap.docs.map(d => ({ id: d.id, ...d.data() })),
        ...secSnap.docs.map(d => ({ id: d.id, ...d.data() }))
    ];

    const rows = fileSnap.docs
        .map(d => ({ id: d.id, ...d.data() }))
        .filter(f => !f.deleted && !f.isSymlink)   // links have no storage of their own
        .map(f => {
            const rec = f.records || {};
            return {
                id:       f.id,
                name:     f.name || 'Untitled',
                type:     f.type || 'txt',
                path:     buildPath(projectName, f.parentId || null, folders, null),
                records: {
                    onedrive:    rec.onedrive    || '',
                    hdPath:      rec.hdPath      || '',
                    customLinks: rec.customLinks || []
                }
            };
        });

    rows.sort((a, b) =>
        a.path.localeCompare(b.path) || a.name.localeCompare(b.name));
    return rows;
}

/*
 * saveRecordsBulk — writes ONLY the rows the user actually edited.
 * Reuses saveItemRecords per row so each change still produces the
 * same per-field log lines diffRecords() generates for single edits;
 * a bulk paste is not a reason to lose that history.
 * Returns { saved, failed:[{id, message}] } rather than throwing, so
 * one bad row can't discard the rest of a long paste session.
 */
async function saveRecordsBulk(pid, changes) {
    let saved = 0;
    const failed = [];
    for (const change of (changes || [])) {
        try {
            await saveItemRecords(pid, 'file', change.id, change.records);
            saved++;
        } catch (e) {
            failed.push({ id: change.id, message: e.message || 'write failed' });
        }
    }
    return { saved, failed };
}


/* ══════════════════════════════════════════════════
   TOUCH ANCESTORS — freshness propagation
   A card shows updatedAt, but updatedAt only ever moved
   when the item ITSELF was edited. Adding a file three
   sections deep never touched the section, the module or
   the project, so their cards froze at the last rename.
   This walks the chain and bumps every ancestor.

   Throttled per target: autosave fires constantly, and
   the display only needs to be roughly current, so one
   write per chain per 60s is plenty.
══════════════════════════════════════════════════ */
const _touchedAt = new Map();
const TOUCH_THROTTLE = 60000;

async function touchAncestors(pid, parentId, opts) {
    const force = opts && opts.force;
    const key   = pid + ':' + (parentId || 'root');
    const last  = _touchedAt.get(key) || 0;
    if (!force && (Date.now() - last) < TOUCH_THROTTLE) return;
    _touchedAt.set(key, Date.now());

    try {
        const stamp = nowFields('updatedAt');

        /* Walk up the folder chain. */
        let cur = parentId || null;
        const seen = new Set();
        while (cur && !seen.has(cur)) {
            seen.add(cur);
            let found = null;
            for (const sub of ['modules', 'sections']) {
                const snap = await getDoc(doc(db, 'projects', pid, sub, cur));
                if (snap.exists()) { found = { sub, data: snap.data() }; break; }
            }
            if (!found) break;
            await merge(doc(db, 'projects', pid, found.sub, cur), { ...stamp });
            cur = found.data.parentId || null;
        }

        /* Always finish at the project, so the landing page card is right. */
        await merge(doc(db, 'projects', pid), { ...stamp });
    } catch (e) {
        console.warn('[touchAncestors]', e.message);
    }
}

/* ══════════════════════════════════════════════════
   SYMLINK CASCADE HELPER
   Given a set of item ids about to be binned, finds every
   pointer aimed at any of them — across ALL projects and
   all three collections — in a single scan. Symlinks live
   in the DESTINATION project, so a parentId-based BFS can
   never see them; they have to be hunted separately.
══════════════════════════════════════════════════ */
/*
 * ── WHY THIS WAS SLOW ─────────────────────────────────
 * The original walked every project and ran three queries inside
 * each one: 1 + 3N round trips for a single delete. At twenty
 * projects that is sixty-one sequential-ish reads before the
 * delete could finish, and it grew every time you made a project.
 * That was the wait.
 *
 * A collection-group query asks the same question across every
 * project at once — three reads, flat, no matter how many projects
 * you own.
 *
 * ── THE INDEX ─────────────────────────────────────────
 * Collection-group queries need their index scope enabled, which
 * Firestore does not do automatically for single fields. Until it
 * exists the query fails with 'failed-precondition' and a console
 * link that creates it in one click.
 *
 * So this falls back to the old per-project walk on that error
 * rather than breaking deletes. Slow, but correct, and it keeps
 * working for anyone who never clicks the link.
 */
async function findSymlinksToAny(targetIds) {
    const wanted = new Set(targetIds);
    if (!wanted.size) return [];

    try {
        return await findSymlinksFast(wanted);
    } catch (e) {
        if (e && e.code === 'failed-precondition') {
            console.warn(
                '[Scribble] Symlink lookup is running the slow way. ' +
                'Open the link in the error above once to create the ' +
                'collection-group index, and deletes get much faster.'
            );
        } else {
            console.warn('[findSymlinksToAny] fast path failed:', e && e.message);
        }
        return findSymlinksSlow(wanted);
    }
}

/* Three queries total, whatever the project count. */
async function findSymlinksFast(wanted) {
    const found = [];
    const hostNames = new Map();

    for (const sub of ['modules', 'sections', 'files']) {
        const snap = await getDocs(query(
            collectionGroup(db, sub),
            where('isSymlink', '==', true)
        ));

        for (const d of snap.docs) {
            const data = d.data();
            if (data.deleted) continue;
            if (!wanted.has(data.targetId)) continue;

            /* The host project id is on the document already; walking
               ref.parent.parent is the fallback for older links written
               before projectId was stored. */
            const hostId = data.projectId ||
                (d.ref.parent && d.ref.parent.parent ? d.ref.parent.parent.id : null);
            if (!hostId) continue;

            found.push({
                id: d.id, _subcol: sub,
                _hostProjectId: hostId,
                _hostProjectName: '—',      // filled below
                ...data
            });
            hostNames.set(hostId, null);
        }
    }

    /* Names are only needed for the links actually found — normally
       none — so this reads a handful of documents rather than all. */
    await Promise.all([...hostNames.keys()].map(async id => {
        try {
            const p = await getDoc(doc(db, 'projects', id));
            if (p.exists()) hostNames.set(id, p.data().name || '—');
        } catch (e) { /* leave the dash */ }
    }));

    found.forEach(f => {
        f._hostProjectName = hostNames.get(f._hostProjectId) || '—';
    });

    return found;
}

/* The original walk. Kept as the fallback for a missing index. */
async function findSymlinksSlow(wanted) {
    const found = [];
    try {
        const projSnap = await getDocs(collection(db, 'projects'));
        await Promise.all(projSnap.docs.map(async function(projDoc) {
            if (projDoc.data().deleted) return;
            for (const sub of ['modules', 'sections', 'files']) {
                try {
                    const snap = await getDocs(query(
                        collection(db, 'projects', projDoc.id, sub),
                        where('isSymlink', '==', true)
                    ));
                    snap.docs.forEach(function(d) {
                        const data = d.data();
                        if (data.deleted) return;
                        if (!wanted.has(data.targetId)) return;
                        found.push({
                            id: d.id, _subcol: sub,
                            _hostProjectId: projDoc.id,
                            _hostProjectName: projDoc.data().name || '—',
                            ...data
                        });
                    });
                } catch(e) { /* unreadable project — skip */ }
            }
        }));
    } catch(e) { console.warn('[findSymlinksToAny]', e.message); }
    return found;
}

/* ══════════════════════════════════════════════════
   REPOINTING LINKS AFTER AN ID CHANGE
   Added 2026-09-17
   ══════════════════════════════════════════════════
   Two operations do not move an item — they COPY it to
   its destination with a freshly minted id and then
   hard-delete the original:

     moveItem()      the cross-project branch
     promoteModule() the module's children

   A symlink stores its target as `targetId`, an id. So
   after either of those, every pointer aimed at the thing
   that moved is holding the id of a document that no
   longer exists. Opening one gives you

     "This link points to a file that no longer exists.
      The original may have been deleted or moved."

   — which is true, unhelpful, and was permanent. Nothing
   ever repointed them. promoteModule's own comment said
   so out loud: "anything pointing at the old ids
   (symlinks) is left behind exactly as a cross-project
   move leaves it."

   Both functions already build an `idMap` of old id → new
   id purely to reparent the children they copy. That map
   is exactly what is needed to follow the links across
   too, so this costs one collection-group query — and for
   most items it finds nothing at all.

   ── WHY THE SAME-PROJECT MOVE NEEDS NOTHING ────────
   moveItem's same-project branch only writes parentId.
   The document keeps its id, so every pointer at it stays
   correct. copyItem needs nothing either: it deletes
   nothing, so the original and its links are untouched.
══════════════════════════════════════════════════ */

/*
 * idMap           old id → new id, for everything that was re-minted
 * newPid          the project those new ids live in
 * newProjectName  denormalised onto the pointer; the symlink card's
 *                 tooltip reads "Linked from <targetProjectName>"
 * whatHappened    tail of the log line written into the HOST project
 */
async function repointSymlinks(idMap, newPid, newProjectName, whatHappened) {
    const oldIds = Object.keys(idMap || {});
    if (!oldIds.length) return 0;

    let pointers;
    try {
        pointers = await findSymlinksToAny(oldIds);
    } catch (e) {
        console.warn('[repointSymlinks] could not look for links:', e.message);
        return 0;
    }

    let fixed = 0;
    for (const ptr of pointers) {
        const newId = idMap[ptr.targetId];
        if (!newId) continue;

        try {
            /* Three fields, because a cross-project move changes all
               three: which document, which project, and the name the
               card displays. */
            await merge(doc(db, 'projects', ptr._hostProjectId, ptr._subcol, ptr.id), {
                targetId:          newId,
                targetProjectId:   newPid,
                targetProjectName: newProjectName || '',
                ...nowFields('updatedAt')
            });

            /* Logged in the project that OWNS the link, since that is
               where someone would go looking for why it changed.
               resolveItemMeta sees isSymlink on the pointer and stamps
               this as kind:'link' on its own. */
            await writeProjectLog(ptr._hostProjectId,
                "Link followed '" + (ptr.name || 'Untitled') + "' " + whatHappened + '.',
                ptr.id);
            fixed++;
        } catch (e) {
            /* A pointer the source project had already hard-deleted can
               still come back from the server for a moment, and merging
               onto a gone document is rejected. Nothing to do about it
               and nothing lost — that copy is on its way out anyway. */
            console.warn('[repointSymlinks] could not repoint', ptr.id, e.message);
        }
    }
    return fixed;
}

/*
 * When there is NO new id to point at — a promoted module becomes a
 * project, and a symlink cannot target a project — the link genuinely
 * cannot be saved. Deleting someone's link on their behalf is worse
 * than leaving it, so this records what happened in the host project's
 * log instead. At least the break is then traceable to a cause.
 */
async function flagBrokenSymlinks(ids, reason) {
    if (!ids || !ids.length) return 0;

    let pointers;
    try {
        pointers = await findSymlinksToAny(ids);
    } catch (e) {
        return 0;
    }

    let n = 0;
    for (const ptr of pointers) {
        try {
            await writeProjectLog(ptr._hostProjectId,
                "Link to '" + (ptr.name || 'Untitled') + "' broke — " + reason + '.',
                ptr.id);
            n++;
        } catch (e) { /* a log line must never be what fails an operation */ }
    }
    return n;
}

/* ══════════════════════════════════════════════════
   SOFT DELETE → BIN
══════════════════════════════════════════════════ */
async function softDeleteItem(pid, itemType, id) {
    invalidateItemIndex(pid);
    touchAncestors(pid, null, { force: true });
    /* 1. Project name for paths */
    const projectSnap = await getDoc(doc(db, 'projects', pid));
    const projectName = projectSnap.exists() ? (projectSnap.data().name || 'Unknown') : 'Unknown';

    /* 2. Fetch all content */
    const [modSnap, secSnap, fileSnap] = await Promise.all([
        getDocs(collection(db, 'projects', pid, 'modules')),
        getDocs(collection(db, 'projects', pid, 'sections')),
        getDocs(collection(db, 'projects', pid, 'files'))
    ]);
    const allItems = [
        ...modSnap.docs.map(d  => ({ id: d.id, _subcol: 'modules',  _type: 'MODULE',  ...d.data() })),
        ...secSnap.docs.map(d  => ({ id: d.id, _subcol: 'sections', _type: 'SECTION', ...d.data() })),
        ...fileSnap.docs.map(d => ({ id: d.id, _subcol: 'files',    _type: 'FILE',    ...d.data() })),
    ];

    /* 3. Find target */
    const targetItem = allItems.find(x => x.id === id);
    if (!targetItem) { console.warn('[softDeleteItem] not found:', id); return; }

    /* 4. BFS: collect target + all descendants */
    const toDelete = [targetItem];
    const queue    = [id];
    const seenIds  = new Set([id]);
    while (queue.length > 0) {
        const current  = queue.shift();
        const children = allItems.filter(x => x.parentId === current && !x.deleted && !seenIds.has(x.id));
        for (const child of children) {
            seenIds.add(child.id);
            toDelete.push(child);
            queue.push(child.id);
        }
    }

    const groupSize = toDelete.length;
    const groupId   = id;
    /* Spread, not assigned — the bin's countdown and "Deleted On"
       both read this, and offline the server value is null. */
    const now       = nowFields('deletedAt');

    /* 5. Write bin entries + mark deleted */
    for (const item of toDelete) {
        const chain = buildParentChain(pid, projectName, item.parentId, allItems);
        const path  = buildPath(projectName, item.parentId, allItems, item.name || 'Untitled');

        add(collection(db, 'bin'), {
            type:        item._type,
            itemId:      item.id,
            projectId:   pid,
            projectName,
            parentId:    item.parentId || null,
            groupId,
            name:        item.name        || 'Untitled',
            fileType:    item._type === 'FILE' ? (item.type || null) : null,
            colour:      item.colour       || null,
            ...now,
            originalPath: path,
            parentChain:  chain,
            groupSize,
            data: {
                name:        item.name        || '',
                description: item.description || '',
                parentId:    item.parentId    || null,
                createdAt:   item.createdAt   || null,
                updatedAt:   item.updatedAt   || null,
                type:        item.type        || null,
                colour:      item.colour      || null,
            }
        });

        await merge(doc(db, 'projects', pid, item._subcol, item.id), {
            deleted: true, ...now
        });
    }

    /* 5b. SYMLINK CASCADE
       Every pointer aimed at anything in this group follows it into the
       bin, in the SAME group, flagged so restore can put it back exactly
       where it lived. Without this a delete leaves dangling links in
       other projects that open into nothing.

       ── NOT AWAITED, ON PURPOSE ────────────────────────
       Everything above has already been queued: the bin entries
       exist and the items are flagged deleted, so the card is gone
       from the grid the moment this line is reached.

       Hunting pointers is cleanup in OTHER projects. Making the
       delete sit and wait for it meant every deletion paid for a
       scan that, for most items, finds nothing at all. It runs on
       its own now and the delete returns immediately.

       Ordering still holds: these writes join the same queue behind
       the ones above, so a pointer never reaches the bin ahead of
       the thing it points at. */
    (async function cascadeSymlinks() {
    try {
        const pointers = await findSymlinksToAny(toDelete.map(x => x.id));
        for (const ptr of pointers) {
            add(collection(db, 'bin'), {
                type:        ptr._subcol === 'modules' ? 'MODULE'
                           : ptr._subcol === 'sections' ? 'SECTION' : 'FILE',
                itemId:      ptr.id,
                projectId:   ptr._hostProjectId,
                projectName: ptr._hostProjectName,
                parentId:    ptr.parentId || null,
                groupId,
                name:        ptr.name || 'Untitled',
                fileType:    ptr.targetType || null,
                colour:      ptr.colour || null,
                ...now,
                originalPath: ptr._hostProjectName + ' / ' + (ptr.name || 'Untitled'),
                parentChain:  [],
                groupSize,
                /* Flags the restore pass: this is a pointer, not content.
                   It is NOT part of the parentId tree and must never be
                   walked by the recursive child restore. */
                isSymlinkPointer: true,
                linkTargetId:     ptr.targetId || null,
                data: {
                    name:              ptr.name || '',
                    description:       ptr.description || '',
                    parentId:          ptr.parentId || null,
                    createdAt:         ptr.createdAt || null,
                    updatedAt:         ptr.updatedAt || null,
                    type:              ptr.type || null,
                    colour:            ptr.colour || null,
                    /* The fields that make it a link at all — the old bin
                       entry dropped these, so a link rebuilt from `data`
                       came back as an empty orphan file. */
                    isSymlink:         true,
                    targetId:          ptr.targetId || null,
                    targetType:        ptr.targetType || null,
                    targetProjectId:   ptr.targetProjectId || null,
                    targetProjectName: ptr.targetProjectName || null,
                }
            });
            await merge(doc(db, 'projects', ptr._hostProjectId, ptr._subcol, ptr.id), {
                deleted: true, ...now
            });
            await writeProjectLog(ptr._hostProjectId,
                "Link followed '" + (targetItem.name || 'Untitled') + "' into the bin.", ptr.id);
        }
    } catch(e) { console.warn('[softDeleteItem] symlink cascade:', e.message); }
    })();

    /* 6. Log */
    const typeLabel = itemType.charAt(0).toUpperCase() + itemType.slice(1);
    await writeProjectLog(pid, 'Moved to bin.', id);

    /* Direct parent (only — not the whole ancestor chain) sees a child
       leave its own boundary, without needing to know it went to the bin. */
    if (targetItem.parentId) {
        await writeProjectLog(pid,
            "'" + (targetItem.name || 'Untitled') + "' removed" +
            (groupSize > 1 ? ' (' + groupSize + ' items).' : '.'),
            targetItem.parentId
        );
    }

    await writeGlobalLog(targetItem.name || 'Untitled');
}

/* ══════════════════════════════════════════════════
   MERGE ITEM  — within same project, same type only
   Re-parents all children of source → target,
   optionally renames target, then soft-deletes source.
══════════════════════════════════════════════════ */
async function mergeItem(pid, itemType, sourceId, targetId, newName) {
    const coll = COLL[itemType]; // 'modules' or 'sections' only
    if (!coll) return;

    // Names for logging
    const [srcSnap, tgtSnap] = await Promise.all([
        getDoc(doc(db, 'projects', pid, coll, sourceId)),
        getDoc(doc(db, 'projects', pid, coll, targetId))
    ]);
    const sourceName = srcSnap.exists() ? (srcSnap.data().name || 'Untitled') : 'Untitled';
    const targetName = tgtSnap.exists() ? (tgtSnap.data().name || 'Untitled') : 'Untitled';

    // Fetch all subcollections to find direct children of source
    const [modSnap, secSnap, fileSnap] = await Promise.all([
        getDocs(collection(db, 'projects', pid, 'modules')),
        getDocs(collection(db, 'projects', pid, 'sections')),
        getDocs(collection(db, 'projects', pid, 'files'))
    ]);

    const now = nowFields('updatedAt');

    // Re-parent direct children of source → target
    for (const d of modSnap.docs) {
        if (d.data().parentId === sourceId && !d.data().deleted)
            await merge(doc(db, 'projects', pid, 'modules', d.id),  { parentId: targetId, ...now });
    }
    for (const d of secSnap.docs) {
        if (d.data().parentId === sourceId && !d.data().deleted)
            await merge(doc(db, 'projects', pid, 'sections', d.id), { parentId: targetId, ...now });
    }
    for (const d of fileSnap.docs) {
        if (d.data().parentId === sourceId && !d.data().deleted)
            await merge(doc(db, 'projects', pid, 'files', d.id),    { parentId: targetId, ...now });
    }

    // Rename target if a new name was given
    const mergedName = (newName && newName.trim()) ? newName.trim() : targetName;
    if (newName && newName.trim()) {
        await merge(doc(db, 'projects', pid, coll, targetId), { name: mergedName, ...now });
    }

    // Source now has no children — soft-delete it cleanly into bin
    await softDeleteItem(pid, itemType, sourceId);

    await writeProjectLog(pid,
        "Merged " + itemType + " '" + sourceName + "' into '" + mergedName + "'",
        targetId
    );
    await writeGlobalLog(mergedName);
}

