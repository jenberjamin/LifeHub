/* ══════════════════════════════════════════════════
   PAGED PROJECT LOG
   Pulls one capped window of recent entries, then filters,
   sorts and pages IN MEMORY — so switching page, flipping a
   filter or reversing the sort costs zero extra reads.

   The old readers were the real scaling problem:
   getItemLogsRecursive re-read modules+sections+files on
   every open, then fired one query per 30-id chunk at
   limit(50) each — a 120-item project meant 3 full
   collection reads plus 4 queries returning up to 200 docs,
   all to display 50. This reads once.
══════════════════════════════════════════════════ */
async function getProjectLogsPaged(pid, opts) {
    const o = opts || {};
    const fetchCap = o.fetchCap || 600;

    let rows = [];
    try {
        const snap = await getDocs(query(
            collection(db, 'projects', pid, 'logs'),
            orderBy('timestamp', 'desc'),
            limit(fetchCap)
        ));
        rows = snap.docs.map(d => {
            const data = d.data();
            /* whenMs, not .toDate() — 2026-09-17. A log line written
               offline has a null server timestamp until it flushes, so
               reading the field direct dated it "—" and sorted it as
               the oldest entry in the project. */
            const _tms = whenMs(data, 'timestamp');
            const ts   = _tms ? new Date(_tms) : null;
            return {
                id:      d.id,
                action:  data.action || '',
                /* schema 1 docs have no kind/weight. Rather than
                   backfilling, they're tagged legacy and shown as-is. */
                legacy:  !data.kind,
                kind:    data.kind   || 'legacy',
                weight:  data.weight || 2,
                itemId:   data.itemId   || null,
                itemName: data.itemName || null,
                itemType: data.itemType || null,
                fileType: data.fileType || null,
                itemPath: data.itemPath || null,
                actorName:    data.actorName    || null,
                actorSurface: data.actorSurface || null,
                ms:      ts ? ts.getTime() : 0,
                date:    ts,
            };
        });
    } catch (e) {
        console.warn('[getProjectLogsPaged]', e.message);
        return { rows: [], total: 0, page: 1, pages: 1, capped: false };
    }

    const capped = rows.length >= fetchCap;

    if (o.itemId)              rows = rows.filter(r => r.itemId === o.itemId);
    if (o.kind && o.kind !== 'all') rows = rows.filter(r => r.kind === o.kind);
    /* minWeight 2 hides content autosaves without deleting them */
    if (o.minWeight)           rows = rows.filter(r => r.weight >= o.minWeight);
    if (o.search) {
        const q = o.search.toLowerCase();
        rows = rows.filter(r =>
            (r.action   || '').toLowerCase().includes(q) ||
            (r.itemName || '').toLowerCase().includes(q) ||
            (r.itemPath || '').toLowerCase().includes(q));
    }

    rows.sort((a, b) => o.sort === 'oldest' ? a.ms - b.ms : b.ms - a.ms);

    const pageSize = o.pageSize || 50;
    const total    = rows.length;
    const pages    = Math.max(1, Math.ceil(total / pageSize));
    const page     = Math.min(Math.max(1, o.page || 1), pages);
    const start    = (page - 1) * pageSize;

    return { rows: rows.slice(start, start + pageSize), total, page, pages, capped };
}

