/* LifeHub — local static server.
   Run:  node LifeHub-homescreen-server.js        then open http://localhost:8080
   Port: node LifeHub-homescreen-server.js 3000   or set PORT=3000

   No dependencies. Node 14+. */

const http = require("http");
const fs = require("fs");
const path = require("path");

const ENTRY = "LifeHub-HomeScreen.html";

/* The project root is wherever LifeHub-HomeScreen.html lives. Work it out
   rather than assuming, so this file runs correctly whether it sits at the
   root or inside JS/ — and from whatever directory you invoke node from. */
function findRoot(){
  let dir = __dirname;
  for (let up = 0; up < 4; up++){
    if (fs.existsSync(path.join(dir, ENTRY))) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return null;
}

const ROOT = findRoot();

if (!ROOT){
  console.error("Could not find " + ENTRY + ".");
  console.error("Looked in " + __dirname + " and its parent folders.");
  console.error("Put this file in the same folder as " + ENTRY + ", or in a subfolder of it.");
  process.exit(1);
}

/* ---- --scan : rebuild JS/homescreen/LifeHub-homescreen-slides.js from CSS/files/slides/ ----
   Each subfolder becomes a theme. Loose images at the top level go to
   "Default", so you can start by just dropping files in. */
if (process.argv.includes("--scan")){
  const SLIDES_DIR = path.join(ROOT, "CSS", "files", "slides");
  const DECK_FILE  = path.join(ROOT, "JS", "homescreen", "LifeHub-homescreen-slides.js");
  const IMAGE = /\.(jpe?g|png|webp|avif|gif)$/i;

  console.log("Project root: " + ROOT);
  console.log("Scanning:     " + SLIDES_DIR);

  if (!fs.existsSync(SLIDES_DIR)){
    fs.mkdirSync(SLIDES_DIR, { recursive: true });
    console.log("\nThat folder didn't exist, so it's been created.");
    console.log("Drop images in it (or in subfolders, one per theme) and scan again.");
    process.exit(0);
  }

  const themes = {};
  const loose = [];

  for (const entry of fs.readdirSync(SLIDES_DIR, { withFileTypes: true })){
    if (entry.isDirectory()){
      const files = fs.readdirSync(path.join(SLIDES_DIR, entry.name))
        .filter(f => IMAGE.test(f))
        .sort()
        .map(f => "CSS/files/slides/" + entry.name + "/" + f);
      if (files.length) themes[entry.name] = files;
    } else if (IMAGE.test(entry.name)){
      loose.push("CSS/files/slides/" + entry.name);
    }
  }

  if (loose.length) themes["Default"] = (themes["Default"] || []).concat(loose);
  if (!Object.keys(themes).length) themes["Default"] = [];

  const body = Object.entries(themes).map(([name, files]) => {
    const list = files.map(f => '    "' + f + '"').join(",\n");
    return '  ' + JSON.stringify(name) + ': [\n' + list + '\n  ]';
  }).join(",\n");

  const out =
`/* LifeHub — slide deck.
   Generated by: node LifeHub-homescreen-server.js --scan
   Edits here are overwritten on the next scan. */

window.LIFEHUB_SLIDES = {
${body}
};
`;

  fs.mkdirSync(path.dirname(DECK_FILE), { recursive: true });
  fs.writeFileSync(DECK_FILE, out);

  console.log("");
  let total = 0;
  for (const [name, files] of Object.entries(themes)){
    total += files.length;
    console.log("  " + name + ": " + files.length + " image" + (files.length === 1 ? "" : "s"));
  }
  if (!total){
    console.log("  (no images found — check they're .jpg, .png, .webp, .avif or .gif)");
  }
  console.log("\nWrote " + DECK_FILE);
  process.exit(0);
}

const PORT = Number(process.argv[2] || process.env.PORT || 8080);

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css":  "text/css; charset=utf-8",
  ".js":   "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".png":  "image/png",
  ".jpg":  "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".gif":  "image/gif",
  ".svg":  "image/svg+xml",
  ".woff2":"font/woff2",
  ".woff": "font/woff",
  ".ttf":  "font/ttf",
  ".ico":  "image/x-icon",
  ".mp4":  "video/mp4",
  ".txt":  "text/plain; charset=utf-8"
};

const server = http.createServer((req, res) => {
  let urlPath;
  try{
    urlPath = decodeURIComponent(new URL(req.url, "http://localhost").pathname);
  } catch (err){
    res.writeHead(400).end("Bad request");
    return;
  }

  if (urlPath === "/") urlPath = "/LifeHub-HomeScreen.html";

  /* keep requests inside the wallpaper folder */
  const filePath = path.join(ROOT, path.normalize(urlPath));
  if (!filePath.startsWith(ROOT)){
    res.writeHead(403).end("Forbidden");
    return;
  }

  fs.stat(filePath, (err, stat) => {
    if (err || !stat.isFile()){
      res.writeHead(404, { "Content-Type": "text/plain; charset=utf-8" });
      res.end("Not found: " + urlPath);
      return;
    }

    const type = TYPES[path.extname(filePath).toLowerCase()] || "application/octet-stream";
    res.writeHead(200, {
      "Content-Type": type,
      "Content-Length": stat.size,
      "Cache-Control": "no-cache"
    });

    const stream = fs.createReadStream(filePath);
    stream.on("error", () => res.destroy());
    stream.pipe(res);
  });
});

server.on("error", (err) => {
  if (err.code === "EADDRINUSE"){
    console.error("Port " + PORT + " is busy. Try: node LifeHub-homescreen-server.js " + (PORT + 1));
  } else {
    console.error(err.message);
  }
  process.exit(1);
});

server.listen(PORT, () => {
  console.log("LifeHub running at http://localhost:" + PORT);
  console.log("Serving " + ROOT);
  console.log("Ctrl+C to stop.");
});
